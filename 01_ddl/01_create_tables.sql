-- CRIAÇÃO DAS SEQUENCES QUE IRÃO SER UTILIZADAS NAS TABELAS


-- SEQ_CARTEIRINHA_BENEFICIARIO
CREATE SEQUENCE seq_carteirinha_beneficiario
START WITH 1
INCREMENT BY 1
NOMAXVALUE
NOCYCLE
NOCACHE;

-- SEQ_NUMERO_GUIA
CREATE SEQUENCE seq_numero_guia
START WITH 50000
INCREMENT BY 1
NOMAXVALUE
NOCYCLE
NOCACHE;

-- CRIAÇÃO DAS TABELAS

-- TABELA PRESTADOR
CREATE TABLE prestador
(
    id_prestador NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome_prestador VARCHAR2(100) NOT NULL,
    tipo_prestador CHAR(1) NOT NULL,
    cpf_cnpj VARCHAR2(14) NOT NULL,
    conselho_classe VARCHAR2(10) NOT NULL,
    numero_conselho VARCHAR2(10) NOT NULL,
    uf_conselho CHAR(2) NOT NULL,
    especialidade VARCHAR2(100) NOT NULL,
    telefone VARCHAR2(20),
    email VARCHAR2(100),
    status_prestador VARCHAR2(20) NOT NULL,
    data_criacao DATE DEFAULT sysdate NOT NULL,
    data_ultima_alteracao DATE DEFAULT sysdate NOT NULL,
    
    CONSTRAINT pk_prestador_id_prestador PRIMARY KEY(id_prestador),
    CONSTRAINT uk_prestador_cpf_cnpj UNIQUE(cpf_cnpj),
    CONSTRAINT cuk_prestador_uf_classe_numero UNIQUE(uf_conselho, numero_conselho, conselho_classe)
);

-- TABELA PLANO
CREATE TABLE plano
(
    id_plano NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome_plano VARCHAR2(100) NOT NULL,
    codigo_ans VARCHAR2(50) NOT NULL,
    tipo_contratacao VARCHAR2(100),
    segmentacao_assistencial VARCHAR2(100) NOT NULL,
    status_plano VARCHAR2(20) NOT NULL,
    data_criacao DATE DEFAULT sysdate NOT NULL,
    data_ultima_alteracao DATE DEFAULT sysdate NOT NULL,
    
    CONSTRAINT pk_plano_id_plano PRIMARY KEY(id_plano),
    CONSTRAINT uk_plano_codigo_ans UNIQUE(codigo_ans)
);

-- TABELA BENEFICIARIO
CREATE TABLE beneficiario
(
       id_beneficiario NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
       id_plano NUMBER(10) NOT NULL,
       nome_beneficiario VARCHAR2(100) NOT NULL,
       cpf VARCHAR2(11) NOT NULL,
       data_nascimento DATE NOT NULL,
       sexo CHAR(1) NOT NULL,
       email VARCHAR2(100),
       telefone VARCHAR2(20),
       numero_carteirinha VARCHAR2(50) NOT NULL,
       data_validade_carteirinha DATE NOT NULL,
       status_beneficiario VARCHAR2(20) NOT NULL,
       data_criacao DATE DEFAULT sysdate NOT NULL,
       data_ultima_alteracao DATE DEFAULT sysdate NOT NULL,
       
       CONSTRAINT pk_beneficiario_id_beneficiario PRIMARY KEY(id_beneficiario),
       CONSTRAINT fk_id_plano FOREIGN KEY(id_plano) REFERENCES plano(id_plano),
       CONSTRAINT uk_beneficiario_cpf UNIQUE(cpf),
       CONSTRAINT ck_beneficiario_data_validade_carteirinha CHECK(data_validade_carteirinha > data_criacao)
);

-- TABELA ITEM
CREATE TABLE item
(
    id_item NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo_tuss VARCHAR2(20) NOT NULL,
    descricao VARCHAR2(200) NOT NULL,
    tipo_item VARCHAR2(50) NOT NULL,
    valor_referencia NUMBER(10, 2) NOT NULL,
    status_item VARCHAR2(20) NOT NULL,
    data_criacao DATE DEFAULT sysdate NOT NULL,
    data_ultima_alteracao DATE DEFAULT sysdate NOT NULL,
    
    CONSTRAINT pk_item_id_item PRIMARY KEY(id_item),
    CONSTRAINT uk_item_codigo_tuss UNIQUE(codigo_tuss),
    CONSTRAINT ck_item_valor_referencia CHECK(valor_referencia > 0)
);

-- TABELA GUIA ATENDIMENTO
CREATE TABLE guia_atendimento
(
    id_guia NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    numero_guia NUMBER(10) NOT NULL,
    id_beneficiario NUMBER(10) NOT NULL,
    id_prestador NUMBER(10) NOT NULL,
    id_plano NUMBER(10) NOT NULL,
    data_hora_entrada DATE NOT NULL,
    data_hora_alta DATE,
    tipo_guia VARCHAR2(50) NOT NULL,
    status_guia VARCHAR2(20),
    
    CONSTRAINT pk_g_atend_id_guia PRIMARY KEY(id_guia),
    CONSTRAINT fk_g_atend_id_beneficiario FOREIGN KEY(id_beneficiario) REFERENCES beneficiario(id_beneficiario),
    CONSTRAINT fk_g_atend_id_prestador FOREIGN KEY(id_prestador) REFERENCES prestador(id_prestador),
    CONSTRAINT fk_g_atend_id_plano FOREIGN KEY(id_plano) REFERENCES plano(id_plano),
    CONSTRAINT uk_g_atend_numero_guia UNIQUE(numero_guia),
    CONSTRAINT ck_g_atend_data_hora_alta CHECK((data_hora_alta >= data_hora_entrada) OR data_hora_alta IS NULL)
)
;
-- TABELA ITEM_GUIA
CREATE TABLE item_guia
(
    id_guia NUMBER(10) NOT NULL,
    sequencia_item NUMBER(10) NOT NULL,
    id_item NUMBER(10) NOT NULL,
    quantidade NUMBER(10) NOT NULL,
    valor_informado NUMBER(10, 2) NOT NULL,
    data_hora_atendimento DATE,
    
    CONSTRAINT cpk_item_guia_id_guia_sequencia PRIMARY KEY(id_guia, sequencia_item),
    CONSTRAINT fk_item_guia_id_guia FOREIGN KEY(id_guia) REFERENCES guia_atendimento(id_guia),
    CONSTRAINT fk_item_guia_id_item FOREIGN KEY(id_item) REFERENCES item(id_item),
    CONSTRAINT ck_item_guia_valor_informado CHECK(valor_informado >= 0)
);